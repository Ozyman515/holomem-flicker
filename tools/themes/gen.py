"""Generate the app's theme code + per-theme launcher icons from tools/themes/themes.json.

  python3 tools/themes/build.py tools/themes/pal.json tools/themes/overrides.json tools/themes/themes.json /tmp/swatches.png
  python3 tools/themes/gen.py

Writes:
  app/src/main/java/com/ozyman/holomemflicker/ThemeData.kt
  app/src/main/res/drawable/ic_fan_<key>.xml            (icon foreground: folding fan + flick swoosh)
  app/src/main/res/mipmap-anydpi-v26/ic_launcher_<key>.xml
  app/src/main/res/values/theme_icon_colors.xml
  AndroidManifest.xml launcher aliases (between the THEME-ALIASES markers)
"""
import json, math, os, re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
APP = os.path.join(ROOT, "app", "src", "main")
themes = json.load(open(os.path.join(os.path.dirname(__file__), "themes.json")))

# Display order: by generation, the way the game groups them. Raden first (default).
ORDER = ["Gen 0", "Gen 1", "GAMERS/Gen 1", "Gen 2", "GAMERS", "Gen 3", "Gen 4", "Gen 5", "holoX",
         "ID Gen 1", "ID Gen 2", "ID Gen 3", "Myth", "Promise", "Advent", "ReGLOSS"]
GROUP_LABEL = {"GAMERS/Gen 1": "GAMERS", "Gen 0": "Gen 0"}


def key_of(short):
    k = short.lower().replace("+", "plus")
    return re.sub(r"[^a-z0-9]", "", k)


rows = []
for cid, t in themes.items():
    rows.append(dict(t, key=key_of(t["short"]), cid=cid))
rows.sort(key=lambda r: (r["short"] != "Raden", ORDER.index(r["group"]) if r["group"] in ORDER else 99, r["cid"]))

# ---------- Kotlin ----------
def c(h):
    return "0xFF" + h.lstrip("#").upper()

kt = ["package com.ozyman.holomemflicker", "",
      "// GENERATED by tools/themes/gen.py from tools/themes/themes.json. Do not edit by hand.", "",
      "class ThemeSpec(",
      "    val key: String, val name: String, val short: String, val group: String,",
      "    val primary: Int, val deep: Int, val soft: Int, val bg: Int, val line: Int,",
      "    val card: Int, val accent: Int, val alert: Int, val night: Int",
      ")", "",
      "object ThemeData {",
      "    val ALL = listOf("]
for r in rows:
    grp = GROUP_LABEL.get(r["group"], r["group"])
    kt.append('        ThemeSpec("%s", "%s", "%s", "%s", %s, %s, %s, %s, %s, %s, %s, %s, %s.toInt()),' % (
        r["key"], r["name"].replace('"', '\\"'), r["short"].replace('"', '\\"'), grp,
        *[c(r[k]) + ".toInt()" for k in ["primary", "deep", "soft", "bg", "line", "card", "accent", "alert"]],
        c(r["night"])))
kt += ["    )", "", "    fun byKey(k: String): ThemeSpec = ALL.firstOrNull { it.key == k } ?: ALL[0]", "}", ""]
open(os.path.join(APP, "java/com/ozyman/holomemflicker/ThemeData.kt"), "w").write("\n".join(kt))

# ---------- icon geometry (108x108 adaptive viewport, keep inside the 66dp safe circle) ----------
CX, CY, R_OUT, R_IN = 54.0, 75.0, 33.0, 7.0
A0, A1, SLATS, GAP = 200.0, 340.0, 7, 2.2   # degrees, screen angles measured clockwise from +x


def pt(r, deg):
    a = math.radians(deg)
    return CX + r * math.cos(a), CY + r * math.sin(a)


def wedge(d0, d1):
    x0, y0 = pt(R_IN, d0); x1, y1 = pt(R_OUT, d0); x2, y2 = pt(R_OUT, d1); x3, y3 = pt(R_IN, d1)
    return ("M%.2f,%.2f L%.2f,%.2f A%.1f,%.1f 0 0,1 %.2f,%.2f L%.2f,%.2f A%.1f,%.1f 0 0,0 %.2f,%.2fZ"
            % (x0, y0, x1, y1, R_OUT, R_OUT, x2, y2, x3, y3, R_IN, R_IN, x0, y0))


step = (A1 - A0) / SLATS
slats = [wedge(A0 + i * step + GAP / 2, A0 + (i + 1) * step - GAP / 2) for i in range(SLATS)]
rx0, ry0 = pt(R_OUT + 1.6, A0 - 1); rx1, ry1 = pt(R_OUT + 1.6, A1 + 1)
rim = "M%.2f,%.2f A%.1f,%.1f 0 0,1 %.2f,%.2f" % (rx0, ry0, R_OUT + 1.6, R_OUT + 1.6, rx1, ry1)
# flick swoosh above the fan, ending in an arrow head pointing right
swoosh = "M27,33 Q52,16 79,27"
head = "M79,27 L71.5,21.5 M79,27 L71,30.5"

colors_xml = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- GENERATED by tools/themes/gen.py -->", "<resources>"]
os.makedirs(os.path.join(APP, "res/drawable"), exist_ok=True)
os.makedirs(os.path.join(APP, "res/mipmap-anydpi-v26"), exist_ok=True)
for r in rows:
    k = r["key"]
    colors_xml.append('    <color name="ic_bg_%s">%s</color>' % (k, r["deep"]))
    parts = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- GENERATED by tools/themes/gen.py: folding fan + flick swoosh, %s theme -->" % r["short"],
             '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
             '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
    for i, s in enumerate(slats):
        fill = r["card"] if i % 2 == 0 else r["line"]
        parts.append('    <path android:fillColor="%s" android:strokeColor="%s" android:strokeWidth="0.8" android:pathData="%s"/>'
                     % (fill, r["primary"], s))
    parts.append('    <path android:strokeColor="%s" android:strokeWidth="2.6" android:strokeLineCap="round" android:pathData="%s"/>'
                 % (r["accent"], rim))
    parts.append('    <path android:fillColor="%s" android:pathData="M%.1f,%.1f m-4,0 a4,4 0 1,0 8,0 a4,4 0 1,0 -8,0"/>'
                 % (r["accent"], CX, CY))
    parts.append('    <path android:strokeColor="%s" android:strokeWidth="3.2" android:strokeLineCap="round" android:pathData="%s"/>'
                 % (r["accent"], swoosh))
    parts.append('    <path android:strokeColor="%s" android:strokeWidth="3.2" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="%s"/>'
                 % (r["accent"], head))
    parts.append("</vector>")
    open(os.path.join(APP, "res/drawable/ic_fan_%s.xml" % k), "w").write("\n".join(parts) + "\n")
    open(os.path.join(APP, "res/mipmap-anydpi-v26/ic_launcher_%s.xml" % k), "w").write(
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by tools/themes/gen.py -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_bg_%s"/>\n'
        '    <foreground android:drawable="@drawable/ic_fan_%s"/>\n'
        '    <monochrome android:drawable="@drawable/ic_fan_%s"/>\n'
        "</adaptive-icon>\n" % (k, k, k))
colors_xml.append("</resources>")
os.makedirs(os.path.join(APP, "res/values"), exist_ok=True)
open(os.path.join(APP, "res/values/theme_icon_colors.xml"), "w").write("\n".join(colors_xml) + "\n")

# ---------- manifest launcher aliases ----------
man_path = os.path.join(APP, "AndroidManifest.xml")
man = open(man_path).read()
aliases = []
for i, r in enumerate(rows):
    aliases.append(
        '        <activity-alias\n'
        '            android:name=".Launcher_%s"\n'
        '            android:targetActivity=".MainActivity"\n'
        '            android:icon="@mipmap/ic_launcher_%s"\n'
        '            android:enabled="%s"\n'
        '            android:exported="true">\n'
        '            <intent-filter>\n'
        '                <action android:name="android.intent.action.MAIN" />\n'
        '                <category android:name="android.intent.category.LAUNCHER" />\n'
        '            </intent-filter>\n'
        '        </activity-alias>' % (r["key"], r["key"], "true" if i == 0 else "false"))
block = "        <!-- THEME-ALIASES:BEGIN (generated by tools/themes/gen.py) -->\n" + "\n".join(aliases) + \
        "\n        <!-- THEME-ALIASES:END -->"
man = re.sub(r"        <!-- THEME-ALIASES:BEGIN.*?THEME-ALIASES:END -->", lambda _: block, man, flags=re.S)
open(man_path, "w").write(man)
print("generated", len(rows), "themes; default =", rows[0]["short"])
